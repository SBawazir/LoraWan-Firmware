long map(long x, long in_min, long in_max, long out_min, long out_max)
{
	return (x - in_min) * (out_max - out_min + 1) / (in_max - in_min + 1) + out_min;
}





void logMessage(const char *msg)
{
	  HAL_UART_Transmit(&huart3, (uint8_t*)msg, strlen(msg), HAL_MAX_DELAY);

}

void sendCommand(const char *cmd)
{
    char msg[128];
    sprintf(msg, "\r\n>>> %s", cmd);
    logMessage(msg);

    HAL_UART_Transmit(&huart6, (uint8_t*)cmd, strlen(cmd), HAL_MAX_DELAY);
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart == &huart6)
    {
        if (rxIndex < RXBUF_SIZE - 1)
        {
            rxBuf[rxIndex++] = rxByte;

            if (rxByte == '\n') // end of line
            {
                rxBuf[rxIndex] = '\0';
                logMessage("<<< Response: ");
                logMessage((char*)rxBuf);
                logMessage("\r\n");

                // detect join success
                if (strstr((char*)rxBuf, "+EVT:JOINED"))
                    joined = 1;

                rxIndex = 0;
            }
        }
        HAL_UART_Receive_IT(&huart6, &rxByte, 1);
    }
}

void asciiToHex(const char *ascii, char *hex)
{
    while (*ascii)
    {
        sprintf(hex, "%02X", (unsigned char)*ascii);
        hex += 2;
        ascii++;
    }
    *hex = '\0';
}

void sendLoRaData(const char *asciiData)
{
    char hexBuf[256];
    char cmd[300];
    asciiToHex(asciiData, hexBuf);
    sprintf(cmd, "AT+SEND=2:%s\r\n", hexBuf);
    sendCommand(cmd);
}




void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc)
{
    if (hadc->Instance == ADC1)
    {
        ADC_VAL[adc_index++] = HAL_ADC_GetValue(hadc);

        if (adc_index < ADC_SAMPLES)
        {
            // Start next sample — still within this 10-sample burst
            HAL_ADC_Start_IT(hadc);
        }
        else
        {
            // Done capturing 10 samples
            uint32_t sum = 0;
            for (uint8_t i = 0; i < ADC_SAMPLES; i++)
                sum += ADC_VAL[i];

            adc_avg = sum / ADC_SAMPLES;
            adc_index = 0;
            adc_ready_flag = 1;
        }
    }
}


void sendADCData(void)
{
    char debugMsg[64];
    sprintf(debugMsg, "Raw ADC average: %lu\r\n", adc_avg);
    logMessage(debugMsg);

    char cmd[64];
    sprintf(cmd, "AT+SEND=2:%04lX\r\n", adc_avg);
    sendCommand(cmd);
}



